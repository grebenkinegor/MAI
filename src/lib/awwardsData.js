export function getRecommendedWebsites(analysis, colors) {
  return mockAwwardsWebsites
    .map(site => ({
      ...site,
      similarity: calculateSimilarity(analysis, colors, site)
    }))
    .sort((a, b) => b.similarity - a.similarity)
    .slice(0, 12);
}

function calculateSimilarity(analysis, colors, site) {
  let score = 70;

  if (analysis.gridType === site.gridType) {
    score += 5;
  }

  if (colors.palette.length > 0 && site.colors.length > 0) {
    const colorMatch = colors.palette.some(c1 =>
      site.colors.some(c2 => colorDistance(c1, c2) < 30)
    );
    if (colorMatch) score += 10;
  }

  if (analysis.whitespacePercent > 60 && site.gridType === 'Ровная') {
    score += 3;
  }

  return Math.min(score, 99) + Math.floor(Math.random() * 3);
}

function colorDistance(hex1, hex2) {
  const rgb1 = hexToRgb(hex1);
  const rgb2 = hexToRgb(hex2);

  return Math.sqrt(
    Math.pow(rgb1[0] - rgb2[0], 2) +
    Math.pow(rgb1[1] - rgb2[1], 2) +
    Math.pow(rgb1[2] - rgb2[2], 2)
  );
}

function hexToRgb(hex) {
  const result = /^#?([a-f\d]{2})([a-f\d]{2})([a-f\d]{2})$/i.exec(hex);
  return result ? [
    parseInt(result[1], 16),
    parseInt(result[2], 16),
    parseInt(result[3], 16)
  ] : [0, 0, 0];
}
